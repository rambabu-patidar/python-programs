import random

# random function return random number from [0,1)
print(random.random())

# randrange return random number in given range
print(random.randrange(10, 100))

# chooses an random choice from the given non empty sequence
fruits = ["Banana", "Mango", "Pineapple", "Cherry"]
print(random.choice(fruits))

